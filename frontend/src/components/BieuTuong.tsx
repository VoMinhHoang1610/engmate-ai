/** Keep the existing Vietnamese icon API while sharing Lucide throughout EngMate. */
export function BieuTuong({
  ten,
  size = 20,
  className = '',
}: {
  ten: string;
  size?: number;
  className?: string;
}) {
  const Icon = icons[ten] ?? Sparkles;
  return <Icon size={size} className={className} strokeWidth={1.7} aria-hidden="true" />;
}
